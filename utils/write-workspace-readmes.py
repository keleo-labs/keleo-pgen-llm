#!/usr/bin/env python3
"""Write navigable READMEs for Keleo content workspaces.

Usage:
    python3 utils/write-workspace-readmes.py practices/ baselines/ reports/
    python3 utils/write-workspace-readmes.py practices/example/ --fix
    python3 utils/write-workspace-readmes.py ../keleo-content-core/ --fix

The default is a dry run. Existing hand-written READMEs are preserved.
"""

import argparse
import json
import os
import re
import subprocess
from pathlib import Path
from urllib.parse import quote

MARKER = "<!-- Generated by write-workspace-readmes.py -->"
VERSION = "1.1.0"
PROJECT = Path(__file__).resolve().parents[1]
PHASES = (
    ("01-analysis-report.md", "Phase 1 analysis of the source material"),
    ("01.5-distilled-essentials.md", "Phase 1.5 distillation of baseline essentials"),
    ("02-mapping-guide.md", "Phase 2 mapping into the Practice Language"),
    ("00-prompt-history.md", "Prompt, sources and decisions behind this workspace"),
)


def link(path):
    return f"[{path.name}]({quote(path.name)})"


def workspaces(path):
    if "reports" in path.parts and (path / "report.md").is_file():
        return [path]
    if path.parent.name in {"practices", "baselines", "reports"}:
        return [path]
    if path.name in {"practices", "baselines", "reports"}:
        folders = sorted(p for p in path.iterdir() if p.is_dir() and not p.is_symlink())
        if path.name == "reports":
            folders += sorted(child for folder in folders for child in folder.iterdir()
                              if child.is_dir() and (child / "report.md").is_file())
        return folders
    return [workspace for kind in ("practices", "baselines", "reports")
            if (path / kind).is_dir() for workspace in workspaces(path / kind)]


def model_index(paths):
    """Index authored models by their declared names, preferring workspace roots."""
    folders = []
    for root in (PROJECT / "baselines", PROJECT / "practices", *paths):
        if root.name in {"baselines", "practices"}:
            folders.extend(p for p in root.iterdir() if p.is_dir())
        elif root.parent.name in {"baselines", "practices"}:
            folders.append(root)
        else:
            folders.extend(workspaces(root))
    index = {}
    for folder in folders:
        if folder.parent.name not in {"baselines", "practices"}:
            continue
        for path in folder.glob("*.json"):
            if path.name.startswith("_") or "change" in path.stem or "catalog" in path.stem:
                continue
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if data.get("kind") not in {"practiceBaseline", "practice", "method"} or not data.get("name"):
                continue
            priority = 0 if path.stem == folder.name else 1
            key = data["name"]
            candidate = (priority, folder.resolve())
            if key not in index or candidate < index[key]:
                index[key] = candidate
    return {name: folder for name, (_, folder) in index.items()}


def git_root(path):
    return next((p for p in (path, *path.parents) if (p / ".git").exists()), None)


def dependency_url(source, target):
    source, target = source.resolve(), target.resolve()
    source_root, target_root = git_root(source), git_root(target)
    if source_root != target_root and target_root:
        remote = subprocess.run(["git", "-C", str(target_root), "remote", "get-url", "origin"],
                                capture_output=True, text=True)
        if remote.returncode == 0:
            value = remote.stdout.strip()
            ssh = re.fullmatch(r"git@([^:]+):(.+?)(?:\.git)?", value)
            if ssh:
                value = f"https://{ssh.group(1)}/{ssh.group(2)}"
            value = value.removesuffix(".git")
            if value.startswith("https://"):
                branch = subprocess.run(["git", "-C", str(target_root), "symbolic-ref", "--short", "refs/remotes/origin/HEAD"],
                                        capture_output=True, text=True)
                ref = branch.stdout.strip().removeprefix("origin/") if branch.returncode == 0 else "main"
                route = "/-/tree/" if "gitlab" in value.lower() else "/tree/"
                return value + route + quote(ref) + "/" + quote(target.relative_to(target_root).as_posix(), safe="/")
    return quote(os.path.relpath(target, source), safe="/") + "/"


def model_document(folder, name):
    if folder is None:
        return None, {}
    for path in folder.glob("*.json"):
        if path.name.startswith("_") or "change" in path.stem or "catalog" in path.stem:
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if data.get("name") == name and data.get("kind") in {"practice", "method", "practiceBaseline"}:
            return path, data
    return None, {}


def model_versions(data):
    return f"version {data.get('version') or 'not recorded'}; schema {data.get('schemaVersion') or 'not recorded'}"


def model_entry(name, source, target, local_file=None):
    if local_file:
        url = quote(local_file.name)
        _, data = model_document(source, name)
    elif target:
        url = dependency_url(source, target)
        _, data = model_document(target, name)
    else:
        return f"- {name} (folder unavailable)"
    note = " (local checkout only; target has no remote)" if (
        not local_file and git_root(source.resolve()) != git_root(target.resolve())
        and not url.startswith("https://")
    ) else ""
    return f"- [{name}]({url}) — {model_versions(data)}{note}"


def method_contents(data, folder, files, index):
    practice_names = list(data.get("practiceNames", []))
    practice_names += [p["name"] for p in data.get("practices", []) if p.get("name")]
    for path in files:
        if path.suffix == ".json" and path.stem != folder.name:
            try:
                practice = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if practice.get("kind") == "practice" and practice.get("name"):
                practice_names.append(practice["name"])
    practice_names = list(dict.fromkeys(practice_names))
    baseline_names = list(data.get("baselinePracticeNames", []))
    if data.get("baselinePracticeName"):
        baseline_names.append(data["baselinePracticeName"])
    for name in dict.fromkeys(practice_names + list(data.get("practiceDependencyNames", []))):
        _, practice = model_document(folder, name)
        if not practice:
            _, practice = model_document(index.get(name), name)
        baseline_names += practice.get("baselinePracticeNames", [])
        if practice.get("baselinePracticeName"):
            baseline_names.append(practice["baselinePracticeName"])
    baselines = []
    for name in baseline_names:
        if name in baselines:
            continue
        baselines.append(name)
        _, baseline = model_document(index.get(name), name)
        baseline_names += baseline.get("baselinePracticeNames", [])
        if baseline.get("baselinePracticeName"):
            baseline_names.append(baseline["baselinePracticeName"])
    return practice_names, baselines


def readme_for(folder, index=None):
    kind = "reports" if "reports" in folder.parts else folder.parent.name
    files = sorted(p for p in folder.iterdir() if p.is_file() and not p.name.startswith("_"))
    by_name = {p.name: p for p in files}
    main = by_name.get(f"{folder.name}.json" if kind != "reports" else f"{folder.name}.md")
    if kind == "reports":
        main = main or by_name.get("report.md")
    if kind != "reports" and main is None:
        candidates = []
        for path in files:
            if path.suffix != ".json" or "change" in path.stem or "catalog" in path.stem:
                continue
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if data.get("kind") in {"practice", "method", "practiceBaseline"}:
                candidates.append(path)
        if len(candidates) == 1:
            main = candidates[0]
    subfolders = sorted(p for p in folder.iterdir() if p.is_dir() and p.name != "assets"
                        and not p.name.startswith(("_", "backup-")))
    if main is None and not files and not subfolders:
        return None

    data = {}
    if main and main.suffix == ".json":
        try:
            data = json.loads(main.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            pass
    title = data.get("name") or folder.name.replace("-", " ").title()
    if kind == "reports" and folder.parent.name != "reports":
        title = f"{folder.parent.name.replace('-', ' ').title()} — {folder.name}"
    category = {"practices": "practice or method", "baselines": "baseline", "reports": "report"}[kind]
    lines = [MARKER, f"## {title}", "", data.get("description") or f"This folder contains the {category} workspace for {title}.", ""]
    used = {"README.md"}
    if main:
        model_kind = {"practiceBaseline": "baseline", "practice": "practice", "method": "method"}.get(data.get("kind"), category)
        description = "report" if kind == "reports" else f"{model_kind} model ({model_versions(data)})"
        lines += ["## Main file", "", f"{link(main)} is the {description}.", ""]
        used.add(main.name)
        practices = []
        if kind == "practices" and data.get("kind") != "method":
            for path in files:
                if path.suffix != ".json" or path.name.startswith("_") or "change" in path.stem:
                    continue
                try:
                    practice = json.loads(path.read_text(encoding="utf-8"))
                except (OSError, ValueError):
                    continue
                if practice.get("kind") == "practice" and practice.get("name"):
                    practices.append((practice["name"], path, practice))
        if len(practices) > 1:
            lines += ["### Practices", "", *(f"- [{name}]({quote(path.name)}) — {model_versions(practice)}"
                                                for name, path, practice in practices), ""]
            used.update(path.name for _, path, _ in practices)
        if data.get("kind") == "method" and index is not None:
            practice_names, baseline_names = method_contents(data, folder, files, index)
            if practice_names:
                lines += ["### Practices", ""]
                for name in practice_names:
                    path, _ = model_document(folder, name)
                    target = index.get(name)
                    lines.append(model_entry(name, folder, target, path))
                    if path:
                        used.add(path.name)
                lines.append("")
            if baseline_names:
                lines += ["### Baselines", ""]
                for name in baseline_names:
                    lines.append(model_entry(name, folder, index.get(name)))
                lines.append("")
        dependencies = []
        if index is not None and kind != "reports":
            names = [] if data.get("kind") == "method" else list(data.get("baselinePracticeNames", []))
            if data.get("baselinePracticeName") and data.get("kind") != "method":
                names.append(data["baselinePracticeName"])
            names += data.get("practiceDependencyNames", [])
            if data.get("kind") == "method":
                names = [name for name in names if name not in practice_names]
            for name in dict.fromkeys(names):
                dependencies.append(model_entry(name, folder, index.get(name)))
        if dependencies:
            lines += ["### Dependencies", "", *dependencies, ""]
    phase_lines = []
    for name, description in PHASES:
        if name in by_name:
            phase_lines.append(f"- {link(by_name[name])} — {description}.")
            used.add(name)
    if phase_lines:
        lines += ["## How it was made", "", *phase_lines, ""]
    others = [p for p in files if p.name not in used and p.suffix.lower() in {".md", ".json", ".pdf", ".docx"}]
    if others:
        lines += ["## Other files", ""]
        for path in others:
            purpose = ("Change request" if "change" in path.stem else
                       "Supporting data" if kind == "reports" and path.suffix == ".json" else
                       "Related model" if path.suffix == ".json" else
                       "Export" if path.suffix.lower() in {".pdf", ".docx"} else "Supporting document")
            detail = ""
            if purpose == "Related model":
                try:
                    related = json.loads(path.read_text(encoding="utf-8"))
                except (OSError, ValueError):
                    related = {}
                if related.get("kind") in {"practice", "method", "practiceBaseline"}:
                    detail = f" ({model_versions(related)})"
            lines.append(f"- {link(path)} — {purpose}{detail}.")
        lines.append("")
    if (folder / "assets").is_dir():
        lines += ["The `assets/` directory holds supporting figures and source assets.", ""]
    if kind == "reports" and not main and subfolders:
        lines += ["## Subfolders", "", *(f"- [{p.name}/]({quote(p.name)}/)" for p in subfolders), ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", action="version", version=VERSION)
    parser.add_argument("paths", nargs="+", type=Path, help="Workspace, kind directory or content repository root")
    parser.add_argument("--fix", action="store_true", help="Write READMEs (default: dry run)")
    args = parser.parse_args()
    counts = {"create": 0, "update": 0, "skip": 0}
    index = model_index(args.paths)
    seen = set()
    for root in args.paths:
        if not root.is_dir():
            parser.error(f"not a directory: {root}")
        for folder in workspaces(root):
            target = folder / "README.md"
            if target.resolve() in seen:
                continue
            seen.add(target.resolve())
            current = target.read_text(encoding="utf-8") if target.exists() else ""
            generated = readme_for(folder, index)
            if not generated or (current and not current.startswith(MARKER)) or current == generated:
                counts["skip"] += 1
                continue
            action = "update" if current else "create"
            counts[action] += 1
            print(f"{action}: {target}")
            if args.fix:
                target.write_text(generated, encoding="utf-8")
    print(" ".join(f"{key}={value}" for key, value in counts.items()))


if __name__ == "__main__":
    main()
